"""Bank 7 (never selected in the original: a stale copy of the fixed bank) for the scene prelude of `jsr $8309`:
the bank-2 code `jsr $9148` (positions, altitude, heading quadrant, sin/cos `jsr $8055`, copies) and `jsr $8558`
(four 8x16 multiplications by shift-add `$814C`) done in one call with tables. Bank 2 `$8309` becomes
`lda #7 / sta $d500 / nop`; bank 7 `$830B: sta $d500 / jmp prelude` (landing), exit `lda #2 / jmp $830B` -> bank 2
continues at `$830E` (nop) and `$830F` as before.

Exactness (RAM, and the carry that `$91AB rol` consumes):
- `$9148` part: the same instructions (copy), except `jsr $8055`.
- sin/cos `$8055`: acc = (8-f)*T(a) + f*T(a+1) (24-bit) = 8*T(a) + f*(T(a+1)-T(a)); tables T8 = 8*T (24-bit, 256
  angles) and fD[f][a] = f*(T(a+1)-T(a)) (16-bit, |.| <= 7*1602). T(a) is the original lookup $810A on the sine
  table $B330/$B371 of the fixed bank (quadrant mirror/negation). Side effects as the original leaves them:
  $75 = a+$40, $76-$78 = cos acc, $2813-$2815 = T8(a+$40), $2816-$2818 = T8(a+$41), $280D = f, $280E = (a+$40)>>6,
  $280F = 0, carry = sign of T(a+$41) (carry out of the last `rol $2818`).
- multiplications: r = (m*|c|) >> 8, negated for c < 0; quarter squares m*b = q(m+b) - q(|m-b|), q(x) = x*x/4.
  Final $AA/$AB = |A|, $AD = $A1, $A8/$A9 = r4, $AC = ((m2*|A|) & $7F) << 1 | c, c = carry rotated in by
  $814C: 0 for A < 0 (carry of its own negation), else the carry at the end of the 3rd original call
  ((B < 0) ? (r3 == 0) : bit 7 of m1*|B|). Temporaries: $2277-$2279, $22A4, $22D2, $2300, $232E (all rewritten
  by the spiral code in banks 10-13 before the routine returns)."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def sine_T(rom):
    """T(a) for a = 0..255 as the original $810A computes it (24-bit)."""
    fixed = rom[-8192:]
    hi = lambda i: fixed[0x1330 + i]
    lo = lambda i: fixed[0x1371 + i]
    out = []
    for a in range(256):
        q = a >> 6
        y = (a & 0x3F) ^ (0, 0x3F, 0, 0x3F)[q]
        v = hi(y) << 8 | lo(y)
        out.append(v if q < 2 else (-v) & 0xFFFFFF)
    return out


def s24(v):
    return v - (1 << 24) if v & 0x800000 else v


def tables(rom):
    T = sine_T(rom)
    T8 = [(8 * s24(t)) & 0xFFFFFF for t in T]
    D = []
    for a in range(256):
        d = s24(T[(a + 1) & 255]) - s24(T[a])
        assert -32768 <= 7 * d < 32768
        D.append(d & 0xFFFF)
    sq = [x * x // 4 for x in range(512)]
    return T8, D, sq


def dta(L, data):
    data = bytes(data)
    for i in range(0, len(data), 16):
        L.append(" dta " + ",".join(f"${b:02x}" for b in data[i:i + 16]))


def mul8(A, m, b, lo, hi, tag):
    """m*b (zero-page operands m, b) -> lo, hi (zero-page/abs targets; None = leave in A (hi) only)."""
    A(f" lda {m}"); A(" sec"); A(f" sbc {b}"); A(f" bcs {tag}d"); A(" eor #$ff"); A(" adc #1")
    A(f"{tag}d tay")
    A(f" lda {m}"); A(" clc"); A(f" adc {b}"); A(" tax"); A(f" bcs {tag}b")
    A(" lda sqlo,x"); A(" sec"); A(" sbc sqlo,y"); A(f" sta {lo}")
    A(" lda sqhi,x"); A(" sbc sqhi,y"); A(f" sta {hi}"); A(f" jmp {tag}e")
    A(f"{tag}b lda sqlo+256,x"); A(" sec"); A(" sbc sqlo,y"); A(f" sta {lo}")
    A(" lda sqhi+256,x"); A(" sbc sqhi,y"); A(f" sta {hi}")
    A(f"{tag}e")


def gen_source(rom):
    b2 = rom[2 * 8192:3 * 8192]
    g = lambda a, n: bytes(b2[a - 0x8000:a - 0x8000 + n])
    # the parts of bank 2 we copy / replace must be the expected original code
    assert g(0x8309, 6) == bytes.fromhex("204891205885")
    b4 = rom[4 * 8192:5 * 8192]
    assert set(b4[0x1141:0x2000]) == {0xFF}, "bank 4 $9141-$9FFF must be free"
    assert g(0x9148, 0x9194 - 0x9148).hex() == (
        "ad87288587ad88284a66874a66874a66874a66878588ad89288589ad8a284a66894a66894a66894a6689858aa533858ba534"
        "c9409007a9ff858c4c8d91068b2a268b2a858cad86282a2a8592")
    assert g(0x9194, 3) == bytes.fromhex("205580")
    tail = g(0x9197, 0x91DF - 0x9197)
    assert tail.hex() == ("ad092885a0ad0a2885a1ad0b2885a2ad0c2885a3a52985a6a5282a26a62a26a6a90638e5a685a6a52448c9806a"
                          "85a4a5236a85a51868690410 05a9004cdc91c9099002a9088d2228").replace(" ", "")
    assert g(0x91DF, 1) == b"\x60"
    T8, D, sq = tables(rom)
    L = ["; generated by tools/gen_scene7.py (scene prelude of jsr $8309 in bank 4 $9141-$9FFF), do not edit",
         " opt h-", " org $9141"]
    L.append(" :($914a-*) dta $ff")
    L.append(" sta $d500"); L.append(" jmp prelude")       # landing from bank 2 $9148 (lda #4 / sta $d500)
    L.append(" :($9200-*) dta $ff")
    L.append("t8lo"); dta(L, [t & 255 for t in T8])
    L.append("t8mi"); dta(L, [t >> 8 & 255 for t in T8])
    L.append("t8hi"); dta(L, [t >> 16 for t in T8])
    L.append("dlo"); dta(L, [d & 255 for d in D])
    L.append("dhi"); dta(L, [d >> 8 for d in D])
    L.append("sqlo"); dta(L, [s & 255 for s in sq])
    L.append("sqhi"); dta(L, [s >> 8 for s in sq])
    L.append(" ert *<>$9b00")
    A = L.append
    A("prelude")
    # ---- $9148..$9193 copied ----
    A(" lda $2887"); A(" sta $87"); A(" lda $2888")
    for _ in range(4):
        A(" lsr"); A(" ror $87")
    A(" sta $88"); A(" lda $2889"); A(" sta $89"); A(" lda $288a")
    for _ in range(4):
        A(" lsr"); A(" ror $89")
    A(" sta $8a"); A(" lda $33"); A(" sta $8b"); A(" lda $34"); A(" cmp #$40"); A(" bcc pr_1")
    A(" lda #$ff"); A(" sta $8c"); A(" jmp pr_2")
    A("pr_1 asl $8b"); A(" rol"); A(" rol $8b"); A(" rol"); A(" sta $8c")
    A("pr_2 lda $2886"); A(" rol"); A(" rol"); A(" sta $92")
    # ---- sin/cos (was jsr $8055) ----
    A(" lda $2886"); A(" sta $75"); A(" lda $2885"); A(" asl"); A(" rol $75"); A(" asl"); A(" rol $75")
    A(" lda $2885"); A(" lsr"); A(" lsr"); A(" lsr"); A(" and #7"); A(" sta $280d")
    A(" lda #0"); A(" sta $280f")

    def fmul(tag):
        """$aa/$ab = f * D(Y) (16-bit signed, |.| <= 7*1602), D copy shifted in $a8/$a9; X = f; Y kept."""
        A(" lda dlo,y"); A(" sta $a8"); A(" lda dhi,y"); A(" sta $a9"); A(" ldx $280d")
        A(" txa"); A(" lsr"); A(f" bcc {tag}0")
        A(" lda $a8"); A(" sta $aa"); A(" lda $a9"); A(" sta $ab"); A(f" jmp {tag}1")
        A(f"{tag}0 lda #0"); A(" sta $aa"); A(" sta $ab")
        for bit in (2, 4):
            A(f"{tag}{bit // 2} asl $a8")                # D *= 2 (no overflow: |4D| < 2^15)
            A(" rol $a9"); A(" txa"); A(f" and #{bit}"); A(f" beq {tag}{bit}")
            A(" clc"); A(" lda $aa"); A(" adc $a8"); A(" sta $aa"); A(" lda $ab"); A(" adc $a9"); A(" sta $ab")
        A(f"{tag}4")
    A(" ldy $75")                                       # sin: a
    fmul("fs")
    A(" clc"); A(" lda t8lo,y"); A(" adc $aa")
    A(" lda t8mi,y"); A(" adc $ab"); A(" sta $2809")
    A(" lda $ab"); A(" and #$80"); A(" beq sc_1"); A(" lda #$ff")
    A("sc_1 adc t8hi,y"); A(" sta $280a")
    A(" lda $75"); A(" clc"); A(" adc #$40"); A(" sta $75"); A(" tay")   # cos: a + $40
    fmul("fc")
    A(" clc"); A(" lda t8lo,y"); A(" adc $aa"); A(" sta $76")
    A(" lda t8mi,y"); A(" adc $ab"); A(" sta $77"); A(" sta $280b")
    A(" lda $ab"); A(" and #$80"); A(" beq sc_2"); A(" lda #$ff")
    A("sc_2 adc t8hi,y"); A(" sta $78"); A(" sta $280c")
    A(" lda t8lo,y"); A(" sta $2813"); A(" lda t8mi,y"); A(" sta $2814"); A(" lda t8hi,y"); A(" sta $2815")
    A(" tya"); A(" lsr"); A(" lsr"); A(" lsr"); A(" lsr"); A(" lsr"); A(" lsr"); A(" sta $280e")   # (a+$40) >> 6
    A(" iny")
    A(" lda t8lo,y"); A(" sta $2816"); A(" lda t8mi,y"); A(" sta $2817"); A(" lda t8hi,y"); A(" sta $2818")
    A(" cmp #$80")                                      # carry = sign of T(a+$41)
    # ---- $9197..$91DE copied (no flags changed before the rol at $91AF) ----
    A(" lda $2809"); A(" sta $a0"); A(" lda $280a"); A(" sta $a1"); A(" lda $280b"); A(" sta $a2")
    A(" lda $280c"); A(" sta $a3")
    A(" lda $29"); A(" sta $a6"); A(" lda $28"); A(" rol"); A(" rol $a6"); A(" rol"); A(" rol $a6")
    A(" lda #$06"); A(" sec"); A(" sbc $a6"); A(" sta $a6")
    A(" lda $24"); A(" pha"); A(" cmp #$80"); A(" ror"); A(" sta $a4"); A(" lda $23"); A(" ror"); A(" sta $a5")
    A(" clc"); A(" pla"); A(" adc #$04"); A(" bpl pr_3"); A(" lda #$00"); A(" jmp pr_4")
    A("pr_3 cmp #$09"); A(" bcc pr_4"); A(" lda #$08")
    A("pr_4 sta $2822")
    # ---- $8558: four products ----
    # |A| -> $aa/$ab (final), |B| -> $ac/$ad (temporary)
    A(" lda $a0"); A(" sta $aa"); A(" lda $a1"); A(" sta $ab"); A(" bpl mu_1")
    A(" sec"); A(" lda #0"); A(" sbc $aa"); A(" sta $aa"); A(" lda #0"); A(" sbc $ab"); A(" sta $ab")
    A("mu_1 lda $a2"); A(" sta $ac"); A(" lda $a3"); A(" sta $ad"); A(" bpl mu_2")
    A(" sec"); A(" lda #0"); A(" sbc $ac"); A(" sta $ac"); A(" lda #0"); A(" sbc $ad"); A(" sta $ad")
    A("mu_2")

    def prod(m, ul, uh, neg_src, dst_lo, dst_hi, tag, keep_plo=None):
        """r = (m*u) >> 8, negated when (neg_src) < 0; stored to dst (abs). keep_plo: store m*ul low byte."""
        # temporaries in the spiral index array $2277-$2279 (every byte rewritten by the bank 10-13 code)
        mul8(A, m, ul, "$2277", "$2278", tag + "a")             # m*ul
        if keep_plo:
            A(" lda $2277"); A(f" sta {keep_plo}")
        mul8(A, m, uh, "$2279", f"{dst_hi}", tag + "b")         # m*uh
        A(" clc"); A(" lda $2278"); A(" adc $2279"); A(f" sta {dst_lo}")
        A(f" lda {dst_hi}"); A(" adc #0"); A(f" sta {dst_hi}")
        A(f" lda {neg_src}"); A(f" bpl {tag}p")
        A(" sec"); A(" lda #0"); A(f" sbc {dst_lo}"); A(f" sta {dst_lo}"); A(" lda #0"); A(f" sbc {dst_hi}")
        A(f" sta {dst_hi}")
        A(f"{tag}p")

    # r1 = $89 * A -> $22a3/$22d1 ; r2 = $87 * B ; $22a3/$22d1 -= r2
    prod("$89", "$aa", "$ab", "$a1", "$22a3", "$22d1", "m1")
    prod("$87", "$ac", "$ad", "$a3", "$2300", "$232e", "m2")       # r2 in point-0 bytes (rewritten later)
    A(" sec"); A(" lda $22a3"); A(" sbc $2300"); A(" sta $22a3"); A(" lda $22d1"); A(" sbc $232e"); A(" sta $22d1")
    # r3 = $89 * B -> $22ff/$232d ; carry at the end of the original 3rd call -> $22a4 (temporary, rewritten later)
    prod("$89", "$ac", "$ad", "$a3", "$22ff", "$232d", "m3", keep_plo="$22a4")
    A(" lda $a3"); A(" bpl m3c")
    A(" lda $22ff"); A(" ora $232d"); A(" beq m3z")     # B < 0: carry = (r3 == 0); r3 here already negated: same test
    A(" lda #0"); A(" beq m3s")
    A("m3z lda #1"); A(" bne m3s")
    A("m3c lda $22a4"); A(" asl"); A(" lda #0"); A(" rol")  # B >= 0: bit 7 of m1*|B| low byte
    A("m3s sta $22d2")                                       # Cin4 (0/1), temporary
    # r4 = $87 * A -> $a8/$a9 (final), plo -> $ac via (plo << 1 | Cin4)
    prod("$87", "$aa", "$ab", "$a1", "$a8", "$a9", "m4", keep_plo="$22a4")
    # $814C rotates the carry into $ac after its own negation of c: for A < 0 that carry is 0 (c != 0)
    A(" lda $22d2"); A(" ldx $a1"); A(" bpl m4c"); A(" lda #0")
    A("m4c lsr"); A(" lda $22a4"); A(" rol"); A(" sta $ac")
    A(" lda $a1"); A(" sta $ad")
    # $22ff/$232d = -(r3 + r4)
    A(" clc"); A(" lda $a8"); A(" adc $22ff"); A(" sta $22ff"); A(" lda $a9"); A(" adc $232d"); A(" sta $232d")
    A(" sec"); A(" lda #0"); A(" sbc $22ff"); A(" sta $22ff"); A(" lda #0"); A(" sbc $232d"); A(" sta $232d")
    A(" lda #2"); A(" jmp $914a")                       # -> bank 2 $914D: jmp $830F
    A(" ert *>$9fff")
    A(" :($9fff-*) dta $ff")
    A(" dta 4")                                         # bank marker for the VBI guard ($BFDA/$BFEA)
    return "\n".join(L) + "\n"


def gen_post(rom):
    """Bank 2: the loop $84FD-$8557 (after the spiral, 6 point pairs from the table $9B09: when one point of a
    pair is behind (class $80) and the other one in view (class 0), the behind one gets z = $0020, class 0)
    unrolled with constant addresses, placed at $8055 (old sin/cos code, unused after scene_pre). Final state as the
    loop leaves it: Y = 12, X = the last loaded index, A, flags of `cpy #12`, $28DB = first index of the last
    pair, $B5 = Y after the last modification."""
    b2 = rom[2 * 8192:3 * 8192]
    assert bytes(b2[0x04FD:0x0558]).hex() == (
        "a000be099b8edb28c8bdb4243023d042be099bc8bdb424103a84b5acdb28a9009d2e23a9209d0023a9009db424a4b5d022be099bc8"
        "bdb424d01984b5acdb28a900992e23a920990023a90099b424a4b5d001c8c00cb0034cff8460")
    T = list(b2[0x1B09:0x1B09 + 12])
    L = ["; generated by tools/gen_scene7.py (bank 2: unrolled post-pass of jsr $8309), do not edit", " opt h-",
         " org $8055"]
    A = L.append
    A(f" lda #{T[10]}"); A(" sta $28db")
    for i in range(6):
        p, q = T[2 * i], T[2 * i + 1]
        last = i == 5
        y = 2 * i + 2

        def modify(t):
            A(f" lda #{y}"); A(" sta $b5")
            A(" lda #0"); A(f" sta ${0x232E + t:04x}"); A(" lda #$20"); A(f" sta ${0x2300 + t:04x}")
            A(" lda #0"); A(f" sta ${0x24B4 + t:04x}")
        A(f" lda ${0x24B4 + p:04x}"); A(f" bmi pp{i}n"); A(f" bne pp{i}s")
        A(f" lda ${0x24B4 + q:04x}"); A(f" bpl pp{i}q")
        modify(q)
        A(f"pp{i}q" + (f" ldx #{q}" if last else "")); A(f" jmp pp{i}e")
        A(f"pp{i}n lda ${0x24B4 + q:04x}"); A(f" bne pp{i}q")
        modify(p); A(f" jmp pp{i}q")
        A(f"pp{i}s" + (f" ldx #{p}" if last else ""))
        A(f"pp{i}e")
    A(" ldy #12"); A(" cpy #12"); A(" rts")
    A(" ert *>$821c")
    return "\n".join(L) + "\n"
