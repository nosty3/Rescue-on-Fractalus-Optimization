"""Generator banku 9 (fill) dla bazy v11: python tools/gen_fill9.py -> src/v11/sky_b9.asm

Fill = dla każdej kolumny bajtowej (42, Y = 3..44 albo 51..92): pierwszy niezerowy wiersz r0 od granicy nieba
D = 152 - HD (wiersz 0 osobno), pas $55 w [D, r0) łańcuchem bk, HD = 152 - min(r0, 44) (152 dla r0 <= 1),
potem propagacja koloru w dół wiersz po wierszu, aż wszystkie 4 piksele miną swój grzbiet.
Funkcja kolumny jest ta sama co w v11 (generator Astry build_fill_rows.py), zmienia się tylko koszt:

- Wiersz pasa w postaci "SK" (11 = piksel jeszcze niebo, 00 = już pod grzbietem):
    out = x ^ (Q[x] & SK),  SK' = Z[x] & SK,  koniec gdy SK' = 0
  gdzie Z = $3A00 (maska pikseli 00), Q[x] = x ^ ($55 | T11[x]), T11 = $3B00 (maska pikseli 11).
  To jest dokładnie stara formuła (x & K) | S | T11[x], S' = Z[x] & S, K' = Z[S'] przy S = SK & $55,
  K = ~SK, o ile $3A00/$3B00 to standardowe tablice (budowane przy starcie gry, potem stałe).
  32-33 cykle na wiersz zamiast 43, bez tabeli K i bez "more".
- Pierwszy wiersz pasa: out = P[x] = $55 | T11[x], SK = Z[x].
- Kolumny 0..40: bez odtwarzania stanu końcowego ($80/$81, $95/$96, C, A, X): nadpisze go ostatnia kolumna.
  Jedyny stan przenoszony między kolumnami to flaga V (ostatnie ADC starego kodu): koniec pasa >= 2 wierszy
  w wierszu j ustawia V jak stare `clc / lda #lo(j-1) / adc #$60` (clv albo bit na bajcie z bitem 6).
- Kolumna 41 (ostatnia): dokładna ścieżka starego kodu (ogólny skan + emulacja first_k + stara pętla
  sky_tail/fallback_loop/column_end), więc A, X, Y, C, V, N, Z, $80, $81, $95, $96, $9F po fillu jak w v11.
- Wiersze 37..47 też mają wyspecjalizowany pierwszy wiersz i łańcuch (stary kod szedł tam pętlą ze wskaźnikiem).
- Skan od D jak dotąd (grupy po 4 wiersze), wejście przez RTS z tablicy po HD (X = HD zostaje do cpx w hit_k).
Scratch: $96 = SK, $97 = k, $98/$99 = wskaźnik trampoliny (martwe po potoku, lista DEAD w equiv.py).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "v11", "sky_b9.asm")
SK = "$96"
LASTY = "$9a"      # Y ostatniej kolumny (x0 + 41), szybka pętla porównuje Y zamiast dec $9f


def row(k):
    return 0x1010 + 96 * k


def hd_of(k):
    return 152 if k <= 1 else 152 - min(k, 44)


def vflag(j):
    """V po starym `clc / lda #lo(row j-1) / adc #$60` (koniec pasa w wierszu j)."""
    a = row(j - 1) & 0xFF
    r = (a + 0x60) & 0xFF
    return bool((a ^ r) & (0x60 ^ r) & 0x80)


def Z(x):
    return sum(3 << (2 * i) for i in range(4) if (x >> (2 * i)) & 3 == 0)


def T11(x):
    return sum(3 << (2 * i) for i in range(4) if (x >> (2 * i)) & 3 == 3)


L = []
e = L.append


def end_fast(j_last):
    """Koniec kolumny w szybkiej ścieżce: następna kolumna albo ostatnia (dokładna)."""
    e(" iny")
    e(f" cpy {LASTY}")
    e(f" beq last_{j_last}")
    e(" jmp column")
    e(f"last_{j_last}")
    e(" jmp lastcol")


e("; Generated by tools/gen_fill9.py (Opus, sesja 2). Nie edytować ręcznie.")
e("; Fill v11 z tańszym pasem (postać SK), bez odtwarzania stanu w kolumnach 0..40; kolumna 41 = stary kod.")
e(" opt h-")
e(" org $8000")
e("entry")
e(" txa")
e(" tay")
e(" lda #0")
e(" sta $0167")
e(" lda #44")         # bez adc: V z wejścia musi przetrwać do pierwszego starego adc
e(" cpx #51")
e(" bcc ly")
e(" lda #92")
e("ly")
e(f" sta {LASTY}")
e("column")
e(" lda $1010,y")
e(" bne f0")
e(" ldx $0100,y")
e(" lda dhi-108,x")
e(" pha")
e(" lda dlo-108,x")
e(" pha")
e(" rts")
# wiersz 0 niezerowy (stary first_0: bez pasa nieba, HD = 152)
e("f0")
e(" tax")
e(" lda P,x")
e(" sta $1010,y")
e(" lda #152")
e(" sta $0100,y")
e(" lda $3a00,x")
e(" bne cont_0")
end_fast(0)
e("cont_0")
e(f" sta {SK}")
for j in range(1, 49):
    R = row(j)
    nxt = f"row_{j + 1}" if j < 48 else "gen49"
    e(f"row_{j}")
    e(f" ldx ${R:04x},y")
    e(" lda Q,x")
    e(f" and {SK}")
    e(f" eor ${R:04x},y")
    e(f" sta ${R:04x},y")
    e(" lda $3a00,x")
    e(f" and {SK}")
    e(f" sta {SK}")
    e(f" bne {nxt}")
    e(" bit setv" if vflag(j) else " clv")
    end_fast(f"r{j}")
    # pierwszy wiersz pasa w wierszu j (stary first_j), spada w row_{j+1}
    e(f"hit_{j}")
    if j >= 2:
        e(f" cpx #{153 - j}")
        e(f" bcc nk_{j}")
        # łańcuch bk{j-1} wpisany do pierwszego punktu kontrolnego (wiersz 4m), dalej jsr w stary łańcuch
        e(" lda #$55")
        jj = j - 1
        stop = 4 * (jj // 4) if jj >= 4 else 1
        for r in range(jj, stop - 1, -1):
            e(f" sta ${row(r):04x},y")
        if jj >= 4:
            e(f" cpx #{153 - stop}")
            e(f" bcc nk_{j}")
            e(f" jsr bk{stop - 1}")
        e(f"nk_{j}")
    e(f" lda #{hd_of(j)}")
    e(" sta $0100,y")
    e(f" ldx ${R:04x},y")
    e(" lda P,x")
    e(f" sta ${R:04x},y")
    e(" lda $3a00,x")
    e(f" bne cont_{j}")
    end_fast(f"h{j}")
    e(f"cont_{j}")
    e(f" sta {SK}")
# wiersze >= 49 (w praktyce martwe: wiersz 48 = $FF zawsze kończy), pętla ze wskaźnikiem jak stary more_48
e("gen49")
e(" clc")
e(" lda #$10")
e(" adc #$60")
e(" sta $80")
e(" lda #$22")
e(" sta $81")
e("gloop")
e(" lda ($80),y")
e(" tax")
e(" lda Q,x")
e(f" and {SK}")
e(" eor ($80),y")
e(" sta ($80),y")
e(" lda $3a00,x")
e(f" and {SK}")
e(f" sta {SK}")
e(" beq gend")
e(" clc")
e(" lda $80")
e(" adc #$60")
e(" sta $80")
e(" bcc gloop")
e(" inc $81")
e(" bcs gloop")
e("gend")
end_fast("g")

# skan od D: grupy po 4 wiersze (jak stary kod), trafienie -> hit_k z X = HD
groups = [list(range(g, min(g + 4, 48))) for g in range(1, 48, 4)]
for gi, grp in enumerate(groups):
    nxtg = f"grp_{groups[gi + 1][0]}" if gi + 1 < len(groups) else "grp_48"
    e(f"grp_{grp[0]}")
    e(f" lda ${row(grp[0]):04x},y")
    for r in grp[1:]:
        e(f" ora ${row(r):04x},y")
    e(f" beq {nxtg}")
    for i, r in enumerate(grp):
        e(f"fs_{r}")
        e(f" lda ${row(r):04x},y")
        e(f" beq {'fs_' + str(r + 1) if i + 1 < len(grp) else nxtg}")
        e(f" jmp hit_{r}")
e("grp_48")
e(" jmp hit_48")

e(" ert * > $930d")
e(" :($930d-*) dta $ff")
e(" jmp entry")
# ostatnia kolumna: dokładna ścieżka starego kodu
e("; ostatnia kolumna: stary kod (ogólny skan, emulacja first_k, sky_tail/fallback_loop/column_end)")
e("lastcol")
e(" lda #1")
e(" sta $9f")
e(" lda #0")
e(" cmp $1010,y")
e(" beq lc_scan")
e(" lda #152")
e(" sta $0100,y")
e(" ldx #0")
e(" jmp sky_tail")
e("lc_scan")
e(" ldx $0100,y")
e(" lda srow-108,x")
e(" tax")
e("lc_loop")
e(" lda rlo,x")
e(" sta $80")
e(" lda rhi,x")
e(" sta $81")
e(" lda ($80),y")
e(" bne lc_found")
e(" inx")
e(" cpx #48")
e(" bne lc_loop")
e("lc_found")
e(" cpx #2")
e(" bcc lc_k1")
e(" stx $97")
e(" lda $0100,y")
e(" cmp t153,x")
e(" bcc lc_nsky")
e(" lda bkl,x")
e(" sta $98")
e(" lda bkh,x")
e(" sta $99")
e(" ldx $0100,y")
e(" lda #$55")
e(" jsr lc_tramp")
e(" ldx $97")
e("lc_nsky")
e(" lda hdt,x")
e(" sta $0100,y")
e(" jmp sky_tail")
e("lc_k1")
e(" lda #152")
e(" sta $0100,y")
e(" jmp sky_tail")
e("lc_tramp")
e(" jmp ($0098)")
# stary ogon (bez zmian): sky_tail, fallback_loop, column_end, done
e("sky_tail")
e(" lda $073d,x")
e(" sta $80")
e(" lda $0793,x")
e(" sta $81")
e(" lda #0")
e(" sta $95")
e(" lda #$55")
e(" sta $96")
e("fallback_loop")
e(" lda ($80),y")
e(" tax")
e(" and $95")
e(" ora $96")
e(" ora $3b00,x")
e(" sta ($80),y")
e(" lda $3a00,x")
e(" and $96")
e(" beq column_end")
e(" sta $96")
e(" tax")
e(" lda $3a00,x")
e(" sta $95")
e(" clc")
e(" lda $80")
e(" adc #$60")
e(" sta $80")
e(" bcc fallback_loop")
e(" inc $81")
e(" bcs fallback_loop")
e("column_end")
e(" iny")
e(" dec $9f")
e(" beq done")
e(" jmp column")
e("done")
e(" php")
e(" pha")
e(" lda $4a")
e(" cmp #2")
e(" bne vinv")
e(" lda #$a5")
e(" bne vset")
e("vinv")
e(" lda #0")
e("vset")
e(" cpy #50")
e(" bcs vb")
e(" sta $0168")
e(" bcc vdone")
e("vb")
e(" sta $0169")
e("vdone")
e(" pla")
e(" plp")
e(" jmp $9ff0")
# łańcuch $55 pasa nieba (bez zmian): wiersze 47..1, A = $55, X = HD, wyjście gdy zapisany wiersz k <= D
e("; łańcuch $55 dla pasa nieba, wiersze 47..1, A = $55, X = HD; wyjście, gdy zapisany wiersz k <= D")
for k in range(47, 0, -1):
    e(f"bk{k}")
    e(f" sta ${row(k):04x},y")
    if k % 4 == 0 and k >= 4:
        e(f" cpx #{152 - k + 1}")
        e(f" bcs bkn{k}")
        e(" rts")
        e(f"bkn{k}")
e(" rts")
# tablice
e(" :($9600-*) dta $ff")
e("P")
e(" dta " + ",".join(f"${0x55 | T11(x):02x}" for x in range(256)))
e("Q")
e(" dta " + ",".join(f"${x ^ (0x55 | T11(x)):02x}" for x in range(256)))
e("; wejście skanu przez RTS (adres - 1) po HD = 108..152 (D = 44..0; D = 0 -> wiersz 1)")
e(" :($986c-*) dta $ff")    # dlo-108 i dhi-108 na tej samej stronie co dane: bez +1 za stronę
fs = [f"fs_{max(152 - h, 1)}" for h in range(108, 153)]
e("dlo")
e(" dta " + ",".join(f"<({f}-1)" for f in fs))
e("dhi")
e(" dta " + ",".join(f">({f}-1)" for f in fs))
e("srow")
e(" dta " + ",".join(str(max(152 - h, 1)) for h in range(108, 153)))
e("rlo")
e(" dta " + ",".join(f"${row(k) & 0xFF:02x}" for k in range(49)))
e("rhi")
e(" dta " + ",".join(f"${row(k) >> 8:02x}" for k in range(49)))
e("t153")
e(" dta " + ",".join(str(153 - k) if k >= 2 else "0" for k in range(49)))
e("hdt")
e(" dta " + ",".join(str(hd_of(k)) for k in range(49)))
e("bkl")
e(" dta " + ",".join(f"<bk{k - 1}" if k >= 2 else "0" for k in range(49)))
e("bkh")
e(" dta " + ",".join(f">bk{k - 1}" if k >= 2 else "0" for k in range(49)))
e("setv")
e(" dta $40")
e(" ert * > $9ff0")
e(" :($9ff0-*) dta $ff")
e(" php")
e(" pha")
e(" lda #2")
e(" sta $d500")
e(" ert * <> $9ff7")
e(" :($9fff-*) dta $ff")
e(" dta 9")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("zapisano", OUT, len(L), "linii")
