"""Relocate verified sound loops into unused bank 2; preserve v2 releases."""
from session import *
import hashlib, subprocess

def build():
 rom=bytearray((ROOT/'build/mountain_cull.rom').read_bytes())
 assert hashlib.sha256(rom).hexdigest()=='fd374e06d8a5ef28a97069408e14d52e8ab9e188706751ec243600447f11a4d0'
 address=0x9d3b;changes=[]
 for entry,kind in [(0xbb19,'minimum'),(0xbb3e,'maximum')]:
  source=(ROOT/f'src/audit_sound_{kind}.asm').read_text()
  source=source.replace('; Standalone audit prototype, NOT patched into distributed game.','; Relocated sound loop, generated by build_lowlevel.py.')
  source=source.replace(f'org ${entry:04x}',f'org ${address:04x}')
  src=ROOT/f'src/lowlevel_sound_{kind}.asm';src.write_text(source)
  binary=ROOT/f'build/lowlevel_sound_{kind}.bin'
  subprocess.run([str(ROOT/'tools/mads/bin/windows_x86_64/mads.exe'),str(src),'-o:'+str(binary)],check=True)
  code=binary.read_bytes();offset=0x4000+address-0x8000
  assert address+len(code)<=0x9fff and all(x==255 for x in rom[offset:offset+len(code)])
  rom[offset:offset+len(code)]=code
  at=0xe000+entry-0xa000;rom[at:at+3]=bytes([0x4c,address&255,address>>8])
  changes.append({'entry':entry,'destination':address,'bytes':len(code)})
  address+=len(code)
 path=ROOT/'build/lowlevel_sound.rom';path.write_bytes(rom)
 out=ROOT/'results/lowlevel';out.mkdir(exist_ok=True)
 (out/'build.json').write_text(json.dumps({'sha256':hashlib.sha256(rom).hexdigest(),'changes':changes},indent=2))
 print('Built',path,changes)

if __name__=='__main__':build()
