"""Generate depth-specialized rasterizer in previously empty XEGS bank 5."""
from cpu_test_support import *
from py65.disassembler import Disassembler
import subprocess,hashlib
import argparse
parser=argparse.ArgumentParser();parser.add_argument('--width3',action='store_true');parser.add_argument('--known-depth',action='store_true');parser.add_argument('--cull',action='store_true');args=parser.parse_args()
variant='mountain_cull' if args.cull else 'mountain_final' if args.known_depth else 'mountain_w3' if args.width3 else 'mountain'
assert not args.known_depth or args.width3,'--known-depth requires --width3'
assert not args.cull or args.known_depth,'--cull requires --known-depth'

base=(ROOT/'build/release.rom').read_bytes()
assert hashlib.sha256(base).hexdigest()=='b2b7e2ad244eb4a127b31640f5e621efc9fc6502805e2f00c6d65871baf13d72'
c=cpu(base);dis=Disassembler(c)
STACK=(0x95,0x96,0xea,0xeb,0xf4,0xf5)
UP={0x98ef,0x990f,0x992d,0x9a18,0x9a36,0x9a52}
DOWN={0x99b3,0x99f7}
DEPTHS=list(range(8))+['g']
lines=['; GENERATED by scripts/build_mountain.py; edit generator, not this file.',
 '; Exact arithmetic and software-stack contents retained.',
 '; Bank 5, eight specialized depths plus general fallback.',
 ' opt h-',' org $8000']

def label(d,pc):return f'd{d}_{pc:04x}'
def emit(lo,hi,d,special=None):
 pc=lo
 while pc<hi:
  n,text=dis.instruction_at(pc);op,mode=c.disassemble[c.memory[pc]]
  prefix=f'{d}_{special}' if special else d
  lines.append(label(prefix,pc))
  if args.width3 and isinstance(d,int) and pc==0x99fa and special is None:
   lines.extend([' cmp #$fd',' beq '+label(f'{d}_split3',0x99fa)])
   # CMP would change carry; ordinary split originally enters with C=0.
   # All widths >3 produce A<$FD, so CMP leaves C=0 on ordinary path.
  if op=='RTS':text='JMP $9900'
  elif mode=='rel' or op=='JMP':
   target=int(text.split('$')[1],16)
   td=d
   if d!='g' and d!='entry':
    if pc in UP:td=d+1 if d<7 else 'g'
    elif pc in DOWN:td=max(0,d-1)
   if d=='entry' and target>=0x986f:td=0
   if special=='split3':
    if pc in UP:
     text='JMP '+label(f'{d}_leaf3',0x99bb)
    else:text=f'{op} {label(prefix,target)}'
   elif special=='leaf3':
    if pc==0x99f7:
     exit_label=f'd{d}_leaf3_exit'
     text='CPX #$D4\n BCS '+exit_label+'\n STX $82\n SEC\n JMP '+label(d,0x9942)+'\n'+exit_label+'\n CLV\n LDX $60\n JMP $9900'
    else:text=f'{op} {label(prefix,target)}'
   else:text=f'{op} {label(td,target)}'
  elif mode=='aby':
   operand=c.memory[pc+1]+256*c.memory[pc+2]
   if operand in STACK and isinstance(d,int):
    actual=d-1 if pc in (0x99ae,0x99f2) else d
    if special=='leaf3':actual=d if pc==0x99f2 else d+1
    if actual>=0:
     assert operand+actual<=255
     text=f'{op} ${operand+actual:02X}'
  if mode=='acc':text=op+' @'
  if args.known_depth and isinstance(d,int):
   if pc in (0x99ab,0x99ef) and special is None and d>0:
    # A specialized positive depth cannot underflow on this pop.
    pc+=n;continue
   if pc in (0x9974,0x99a8,0x99ec):
    # Preserve the original $B5 store, but restore Y one cycle faster.
    known=d+1 if special=='leaf3' else d
    text=f'LDY #{known}'
  # split3 is entered after CMP #$FD with C=1, but original midpoint ADC
  # needs C=0. Explicitly restore it before the first TXA.
  if special=='split3' and pc==0x99fa:lines.append(' clc')
  if special=='leaf3' and pc==0x99ef:
   # Child depth is d+1: pop returns to nonnegative parent depth d.
   pc+=n;continue
  lines.append(' '+text)
  pc+=n

emit(0x982a,0x986f,'entry')
lines.append(' jmp '+label(0,0x986f))
for depth in DEPTHS:
 emit(0x986f,0x9a55,depth)
 if args.width3 and isinstance(depth,int):
  emit(0x99fa,0x9a55,depth,'split3')
  emit(0x99bb,0x99fa,depth,'leaf3')
if args.cull:
 from functools import lru_cache
 @lru_cache(None)
 def extra(w):return 0 if w<=2 else w//4+1+max(extra(w//2),extra((w+1)//2))
 lines+='''cull_entry
 stx $60
 lda $95
 cmp $82
 bcc cull_fallback
 beq cull_fallback
 ldx $82
 cpx #44
 bcc cull_fallback
 cmp #212
 bcs cull_fallback
 sec
 sbc $82
 tay
 lda cull_extra,y
 sta $b5
 lda $84
 cmp $ea
 bcs cull_max
 lda $ea
cull_max
 clc
 adc $b5
 bcc cull_bound
 lda #255
cull_bound
 sta $b5
cull_scan
 lda $260e,x
 cmp $b5
 bcc cull_fallback
 inx
 cpx $95
 bcc cull_scan
 ldx $60
 jmp $9900
cull_fallback
 ldx $60
 jmp dentry_982a
cull_extra'''.splitlines()
 for i in range(0,256,16):lines.append(' dta '+','.join(str(extra(w)) for w in range(i,i+16)))
lines+=['code_end',' ert * > $982f',' :($982f-*) dta $ff',' jmp '+('cull_entry' if args.cull else 'dentry_982a'),
 ' :($9900-*) dta $ff',' php',' pha',' lda #2',' sta $d500',
 '; Execution continues in bank 2 at $9907 (PLA/PLP/RTS).']
src=ROOT/f'src/{variant}.asm';src.write_text('\n'.join(lines)+'\n')
out=ROOT/f'build/{variant}.bin'
r=subprocess.run([str(ROOT/'tools/mads/bin/windows_x86_64/mads.exe'),str(src),'-o:'+str(out),'-l:'+str(ROOT/f'build/{variant}.lst')],capture_output=True,text=True)
assert r.returncode==0,r.stdout+r.stderr
code=out.read_bytes();assert len(code)<=8192
rom=bytearray(base);assert rom[5*8192:6*8192]==b'\xff'*8192
rom[5*8192:5*8192+len(code)]=code
# VBI calls $9B99 (and can read the message at $9C1A) without changing
# the foreground bank. Mirror the original tail so interrupts are safe
# throughout bank-5 rendering, including sound updates and text accesses.
rom[5*8192+0x1907:6*8192]=base[0x5907:0x6000]
# Switch banks at mirrored instruction addresses. No fixed-bank changes needed.
# Entry A/N/Z are dead: original starts STX $60 / LDA $95 / CMP.
rom[0x582a:0x582f]=bytes.fromhex('a9058d00d5')
# Preserve all return registers/flags while restoring bank 2.
rom[0x5907:0x590a]=bytes.fromhex('682860')
# RAM interrupt routines can execute through $7FFF into cartridge byte $8000,
# and call several bank-2 helpers. A full VBI bank guard covers all such paths.
guard_out=ROOT/'build/mountain_vbi.bin'
r=subprocess.run([str(ROOT/'tools/mads/bin/windows_x86_64/mads.exe'),str(ROOT/'src/mountain_vbi.asm'),'-o:'+str(guard_out)],capture_output=True,text=True)
assert r.returncode==0,r.stdout+r.stderr
guard=guard_out.read_bytes();assert len(guard)<=32
assert base[0xffda:0xffda+len(guard)]==b'\xff'*len(guard)
rom[0xffda:0xffda+len(guard)]=guard
assert base[0xf46c:0xf470]==bytes.fromhex('a90085c7')
rom[0xf46c:0xf470]=bytes.fromhex('4cdabfea')
for offset in (0xf4ef,0xf737):
 assert base[offset:offset+3]==bytes.fromhex('4c62e4')
 rom[offset:offset+3]=bytes.fromhex('4ceabf')
assert base[0x5fff]==255
rom[0xbfff]=5
(ROOT/f'build/{variant}.rom').write_bytes(rom)
print('Bank 5 payload',len(code),'SHA256',hashlib.sha256(rom).hexdigest())


