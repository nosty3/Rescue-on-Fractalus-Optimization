"""Extend bank-5 rasterizer with exact width-4/5 paths at selected depths."""
from opt14_common import *
from opt14_cpu import machine
from py65.disassembler import Disassembler
import argparse
p=argparse.ArgumentParser();p.add_argument('--depths',default='1,2,3,4');args=p.parse_args();DEP={int(s) for s in args.depths.split(',') if s}
base=(ROOT/'build/opt14_division.rom').read_bytes();v1=(ROOT/'build/release.rom').read_bytes();c=machine(v1,[0]*65536);dis=Disassembler(c)
STACK=(0x95,0x96,0xea,0xeb,0xf4,0xf5);UP={0x98ef,0x990f,0x992d,0x9a18,0x9a36,0x9a52};DOWN={0x99b3,0x99f7}
lines=['; Generated by build_opt14_width45.py. Bank 5, no extra bank switches.',' opt h-',' org $8000']
def label(d,pc):return f'd{d}_{pc:04x}'
def emit(lo,hi,d,special=None):
 pc=lo;prefix=f'{d}_{special}' if special else d
 while pc<hi:
  n,text=dis.instruction_at(pc);op,mode=c.disassemble[c.memory[pc]];lines.append(label(prefix,pc))
  if isinstance(d,int) and pc==0x99fa and special is None:
   if d in DEP:
    lines.extend([' cmp #$fb',f' bcc ordinary_{d}',' cmp #$fd',' beq '+label(f'{d}_split3',0x99fa),' cmp #$fc',f' bne width5_{d}',' jmp '+label(f'{d}_split4',0x99fa),f'width5_{d}',' jmp '+label(f'{d}_split5',0x99fa),f'ordinary_{d}'])
   else:lines.extend([' cmp #$fd',' beq '+label(f'{d}_split3',0x99fa)])
  if op=='RTS':text='JMP $9900'
  elif mode=='rel' or op=='JMP':
   target=int(text.split('$')[1],16);td=d
   if isinstance(d,int):
    if pc in UP:td=d+1 if d<7 else 'g'
    elif pc in DOWN:td=max(0,d-1)
   if d=='entry' and target>=0x986f:td=0
   if special and special.startswith('split'):
    width=int(special[-1])
    if pc in UP:text=('SEC\n ' if width!=3 else '')+'JMP '+label(f'{d}_leaf{width}',0x99bb if width==3 else 0x9942)
    else:text=f'{op} {label(prefix,target)}'
   elif special and special.startswith('leaf'):
    width=int(special[-1]);end=0x99f7 if width==3 else 0x99b3
    if pc==end:
     exit_label=f'd{prefix}_exit';dest=label(f'{d}_split3',0x99fa) if width==5 else label(d,0x9942)
     text=f'CPX #$D4\n BCS {exit_label}\n STX $82\n SEC\n JMP {dest}\n{exit_label}\n'+(' CLV\n' if width==3 else '')+' LDX $60\n JMP $9900'
    else:text=f'{op} {label(prefix,target)}'
   else:text=f'{op} {label(td,target)}'
  elif mode=='aby':
   operand=c.memory[pc+1]+256*c.memory[pc+2]
   if operand in STACK and isinstance(d,int):
    actual=d-1 if pc in (0x99ae,0x99f2) else d
    if special and special.startswith('leaf'):actual=d if pc in (0x99ae,0x99f2) else d+1
    if actual>=0:text=f'{op} ${operand+actual:02x}'
  if mode=='acc':text=op+' @'
  if isinstance(d,int):
   if pc in (0x99ab,0x99ef) and ((special is None and d>0) or (special and special.startswith('leaf'))):pc+=n;continue
   if pc in (0x9974,0x99a8,0x99ec):text=f'LDY #{d+1 if special and special.startswith("leaf") else d}'
  if special and special.startswith('split') and pc==0x99fa:lines.append(' clc')
  lines.append(' '+text);pc+=n
emit(0x982a,0x986f,'entry');lines.append(' jmp '+label(0,0x986f))
for d in list(range(8))+['g']:
 emit(0x986f,0x9a55,d)
 if isinstance(d,int):emit(0x99fa,0x9a55,d,'split3');emit(0x99bb,0x99fa,d,'leaf3')
# Reuse the proven conservative culling body and table, before its padding.
s=(ROOT/'src/mountain_cull.asm').read_text();lines+=s[s.index('cull_entry\n'):s.index('code_end\n')].splitlines()
lines+=[' ert * > $982f',' :($982f-*) dta $ff',' jmp cull_entry',' :($9900-*) dta $ff',' php',' pha',' lda #2',' sta $d500',' :($990a-*) dta $ff']
for d in sorted(DEP):
 for w in (4,5):emit(0x99fa,0x9a55,d,f'split{w}');emit(0x9942,0x99b9,d,f'leaf{w}')
lines+=[' ert * > $9fff',' :($9fff-*) dta $ff',' dta 5']
code=assemble('opt14_width45','\n'.join(lines)+'\n');assert len(code)==8192
rom=bytearray(base);rom[5*8192:6*8192]=code;save('opt14_width45',rom,base='opt14_division',depths=sorted(DEP))
