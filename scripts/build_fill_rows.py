"""Bank-9 filler with row-specialized addressing; exact binary-mode arithmetic."""
from session import *
import subprocess,hashlib
base=(ROOT/'dist/Rescue on Fractalus! - PAL optimized v4 128KB.rom').read_bytes();rom=bytearray(base)
assert hashlib.sha256(base).hexdigest()=='268a401d9bb0cfdffa627adec73ef79b901c7d08813cefa4426eba24ce8713f2'
address=lambda row:0x1010+96*row
lines=['; Generated by build_fill_rows.py. Game renderer runs with D=0.',
 '; Rows 0..32 use specialized first iterations, later starts use exact fallback.',
 ' opt h-',' org $8000','entry',' txa',' tay',' lda #42',' sta $9f','column',' lda #0',f' cmp ${address(0):04x},y',' beq group_1',' jmp first_0']
for first in range(1,48,4):
 end=min(first+4,48)
 lines += [f'group_{first}',f' lda ${address(first):04x},y']
 lines += [f' ora ${address(r):04x},y' for r in range(first+1,end)]
 lines += [f' beq group_{end}',' lda #0']
 for r in range(first,end):lines += [f' cmp ${address(r):04x},y',f' beq scan_next_{r}',f' jmp first_{r}',f'scan_next_{r}']
lines += ['group_48',' sec',' jmp first_48']
for r in range(33):
 a=address(r)
 lines += [f'first_{r}',' lda #$55']
 lines += [f' sta ${address(k):04x},y' for k in range(r-1,0,-1)]
 lines += [f' lda #${a&255:02x}',' sta $80',f' lda #${a>>8:02x}',' sta $81',' lda #0',' sta $95',' lda #$55',' sta $96',f' lda ${a:04x},y',' tax',' lda $3b00,x',' ora #$55',f' sta ${a:04x},y',' lda $3a00,x',' and #$55',f' bne more_first_{r}',' jmp column_end',f'more_first_{r}',' sta $96',' tax',' lda $3a00,x',' sta $95',f' jmp row_{r+1}']
for r in range(33,49):lines += [f'first_{r}',' lda #$55',f' ldx #{r}',f' jmp sky_{r-1}']
for r in range(47,0,-1):lines += [f'sky_{r}',f' sta ${address(r):04x},y']
lines += [' lda $073d,x',' sta $80',' lda $0793,x',' sta $81',' lda #0',' sta $95',' lda #$55',' sta $96','fallback_loop',' lda ($80),y',' tax',' and $95',' ora $96',' ora $3b00,x',' sta ($80),y',' lda $3a00,x',' and $96',' beq column_end',' sta $96',' tax',' lda $3a00,x',' sta $95',' clc',' lda $80',' adc #$60',' sta $80',' bcc fallback_loop',' inc $81',' bcs fallback_loop',
 'column_end',' iny',' dec $9f',' beq done',' jmp column','done',' jmp $9ff0',' ert * > $930d',' :($930d-*) dta $ff',' jmp entry',' :($9400-*) dta $ff']
for r in range(1,49):
 a=address(r);prev=address(r-1)
 lines += [f'row_{r}',f' lda ${a:04x},y',' tax',' and $95',' ora $96',' ora $3b00,x',f' sta ${a:04x},y',' lda $3a00,x',' and $96',f' bne more_{r}',
 '; Reconstruct only the final pointer and ADC carry/overflow.',
 ' clc',f' lda #${prev&255:02x}',' adc #$60',' sta $80',f' lda #${a>>8:02x}',' sta $81',' lda #0',' jmp column_end',f'more_{r}',' sta $96',' tax',' lda $3a00,x',' sta $95']
a=address(49);prev=address(48)
lines += [' clc',f' lda #${prev&255:02x}',' adc #$60',' sta $80',f' lda #${a>>8:02x}',' sta $81',' jmp fallback_loop',' ert * > $9ff0',' :($9ff0-*) dta $ff',' php',' pha',' lda #2',' sta $d500',' ert * <> $9ff7',' :($9fff-*) dta $ff',' dta 9']
src=ROOT/'src/fill_rows.asm';src.write_text('\n'.join(lines)+'\n');out=ROOT/'build/fill_rows.bin'
subprocess.run([str(ROOT/'tools/mads/bin/windows_x86_64/mads.exe'),str(src),'-o:'+str(out)],check=True)
code=out.read_bytes();assert len(code)==8192 and rom[9*8192:10*8192]==b'\xff'*8192
rom[9*8192:10*8192]=code
assert rom[0x5308:0x530b]==bytes.fromhex('4c429c')
rom[0x5308:0x530d]=bytes.fromhex('a9098d00d5')
assert rom[0x5ff7:0x5ffa]==b'\xff'*3
rom[0x5ff7:0x5ffa]=bytes.fromhex('682860')
assert rom[0x1ffeb:0x1ffef]==bytes.fromhex('c9099002')
rom[0x1ffec]=10
(ROOT/'build/fill_rows.rom').write_bytes(rom)
(ROOT/'build/fill_rows.car').write_bytes(b'CART'+(14).to_bytes(4,'big')+(sum(rom)&0xffffffff).to_bytes(4,'big')+bytes(4)+rom)
dest=ROOT/'results/fill_rows';dest.mkdir(exist_ok=True)
(dest/'build.json').write_text(json.dumps({'sha256':hashlib.sha256(rom).hexdigest(),'code_bank':9,'rom_bytes':len(rom)},indent=2));print('Built',hashlib.sha256(rom).hexdigest())
